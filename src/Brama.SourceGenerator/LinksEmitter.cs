using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Brama.SourceGenerator;

/// <summary>One named endpoint, and the route parameters a link to it needs.</summary>
internal sealed record NamedRoute(string Name, IReadOnlyList<(string Type, string Name)> Parameters);

/// <summary>
/// Emits one <c>Links</c> method per named endpoint, so a handler links to another endpoint by
/// calling a method the compiler checks rather than by interpolating a URL.
/// </summary>
/// <remarks>
/// Both halves it needs are literals in source: the name from <c>Named("GetOrder")</c> and the
/// parameters from the route template's own placeholders. What it cannot know is the finished path —
/// the group prefix and version segment come from the config tree, which does not exist until the
/// application runs — so the generated method defers to ASP.NET Core's link generation at runtime.
/// The magic string at the call site is what disappears, not the lookup.
/// </remarks>
internal static class LinksEmitter
{
    public static bool IsCandidate(SyntaxNode node) =>
        node is InvocationExpressionSyntax
        {
            Expression: MemberAccessExpressionSyntax { Name: GenericNameSyntax },
        };

    public static NamedRoute? NamedRouteOf(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        var invocation = (InvocationExpressionSyntax)context.Node;

        if (invocation.Expression is not MemberAccessExpressionSyntax access
            || !access.Name.Identifier.ValueText.StartsWith("Map", StringComparison.Ordinal)
            || invocation.ArgumentList.Arguments.Count == 0)
        {
            return null;
        }

        if (context.SemanticModel.GetSymbolInfo(invocation, cancellationToken).Symbol is not IMethodSymbol method
            || method.ContainingType?.ToDisplayString() is not ("Brama.Configuration.ConfigNode"
                or "Brama.Configuration.ApiConfig" or "Brama.Configuration.EndpointGroup"))
        {
            return null;
        }

        if (LiteralString(invocation.ArgumentList.Arguments[0].Expression) is not { } template
            || FindName(invocation) is not { } name)
        {
            return null;
        }

        return new NamedRoute(name, ParametersOf(template));
    }

    public static string Emit(IEnumerable<NamedRoute> routes)
    {
        var body = new StringBuilder();
        var emitted = new HashSet<string>(StringComparer.Ordinal);

        foreach (NamedRoute route in routes.OrderBy(route => route.Name, StringComparer.Ordinal))
        {
            if (!emitted.Add(route.Name))
            {
                continue;
            }

            string parameters = string.Concat(route.Parameters.Select(p => $", {p.Type} {p.Name}"));
            string values = route.Parameters.Count == 0
                ? "null"
                : "new { " + string.Join(", ", route.Parameters.Select(p => p.Name)) + " }";

            body.AppendLine();
            body.AppendLine($"    /// <summary>The path of the <c>{route.Name}</c> endpoint.</summary>");
            body.AppendLine($"    public static string {route.Name}(global::Brama.IEndpointContext context{parameters}) =>");
            body.AppendLine($"        context.PathTo(\"{route.Name}\", {values});");
        }

        return $$"""
            // <auto-generated/>
            #nullable enable

            namespace Brama.Generated;

            /// <summary>
            /// A compile-checked path for every endpoint given a name with <c>Named(...)</c>.
            /// </summary>
            public static class Links
            {{{body.ToString().TrimEnd()}}
            }
            """;
    }

    /// <summary>Finds <c>Named("…")</c> in the endpoint's configure lambda.</summary>
    private static string? FindName(InvocationExpressionSyntax invocation)
    {
        foreach (InvocationExpressionSyntax call in invocation.DescendantNodes().OfType<InvocationExpressionSyntax>())
        {
            if (call.Expression is MemberAccessExpressionSyntax { Name.Identifier.ValueText: "Named" }
                && call.ArgumentList.Arguments.Count == 1
                && LiteralString(call.ArgumentList.Arguments[0].Expression) is { } name)
            {
                return name;
            }
        }

        return null;
    }

    /// <summary>
    /// The route template's own placeholders, typed from their route constraint. An unconstrained
    /// placeholder is a string, which is what ASP.NET Core's routing would treat it as anyway.
    /// </summary>
    private static List<(string Type, string Name)> ParametersOf(string template)
    {
        var parameters = new List<(string Type, string Name)>();

        foreach (string segment in template.Split('/'))
        {
            if (!segment.StartsWith("{", StringComparison.Ordinal) || !segment.EndsWith("}", StringComparison.Ordinal))
            {
                continue;
            }

            string inner = segment.Substring(1, segment.Length - 2).TrimEnd('?');
            string[] parts = inner.Split(':');
            string name = parts[0];

            if (name.Length == 0 || name.StartsWith("*", StringComparison.Ordinal))
            {
                continue;
            }

            string type = parts.Length > 1 ? TypeForConstraint(parts[1]) : "string";
            parameters.Add((type, name));
        }

        return parameters;
    }

    private static string TypeForConstraint(string constraint) => constraint switch
    {
        "guid" => "global::System.Guid",
        "int" => "int",
        "long" => "long",
        "bool" => "bool",
        "double" => "double",
        "decimal" => "decimal",
        "datetime" => "global::System.DateTime",
        _ => "string",
    };

    private static string? LiteralString(ExpressionSyntax expression) =>
        expression is LiteralExpressionSyntax { Token.Value: string value } ? value : null;
}
