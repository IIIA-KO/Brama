using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;

namespace Brama.SourceGenerator;

/// <summary>
/// Emits a module's <c>Add{Module}(IServiceCollection)</c> extension method, with every service it
/// declared written out as a literal registration.
/// </summary>
internal static class ModuleEmitter
{
    private const string ModuleAttributeName = "Brama.ModuleAttribute";
    private const string RegisterAllAttributeName = "Brama.RegisterAllAttribute";

    public static bool IsCandidate(SyntaxNode node) =>
        node is Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax { AttributeLists.Count: > 0 };

    public static INamedTypeSymbol? ModuleOf(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        if (context.SemanticModel.GetDeclaredSymbol(context.Node, cancellationToken) is not INamedTypeSymbol type)
        {
            return null;
        }

        bool isModule = type.GetAttributes()
            .Any(attribute => attribute.AttributeClass?.ToDisplayString() == ModuleAttributeName);

        return isModule ? type : null;
    }

    public static (string HintName, string Source) Emit(INamedTypeSymbol module, Compilation compilation)
    {
        string ns = module.ContainingNamespace.IsGlobalNamespace
            ? "Brama.Generated"
            : module.ContainingNamespace.ToDisplayString();

        AttributeData[] requests = [.. module.GetAttributes()
            .Where(attribute => attribute.AttributeClass?.ToDisplayString() == RegisterAllAttributeName)];

        // Walked once per module, not once per [RegisterAll]: this runs on every keystroke in the
        // IDE, and a per-attribute sweep of every type in the assembly is how a generator earns a
        // reputation for making the editor stutter.
        List<INamedTypeSymbol> candidates = requests.Length == 0 ? [] : [.. ConcreteTypesIn(compilation)];

        var body = new StringBuilder();
        foreach (AttributeData request in requests)
        {
            AppendRegistrations(body, request, candidates);
        }

        if (body.Length == 0)
        {
            body.AppendLine("        // This module declared no [RegisterAll(...)] services.");
        }

        string source = $$"""
            // <auto-generated/>
            #nullable enable

            using Microsoft.Extensions.DependencyInjection;

            namespace {{ns}};

            /// <summary>Service registration for the <c>{{module.Name}}</c> module.</summary>
            public static class {{module.Name}}ServiceCollectionExtensions
            {
                /// <summary>
                /// Registers everything the <c>{{module.Name}}</c> module declared. The implementations below
                /// were found when this assembly was compiled; nothing is scanned at run time.
                /// </summary>
                public static IServiceCollection Add{{module.Name}}(this IServiceCollection services)
                {
            {{body.ToString().TrimEnd()}}

                    return services;
                }
            }
            """;

        return ($"{module.Name}.Module.g.cs", source);
    }

    private static void AppendRegistrations(
        StringBuilder body,
        AttributeData request,
        List<INamedTypeSymbol> candidates)
    {
        if (request.ConstructorArguments.Length == 0
            || request.ConstructorArguments[0].Value is not INamedTypeSymbol serviceType)
        {
            return;
        }

        string lifetime = LifetimeOf(request);

        foreach (INamedTypeSymbol implementation in candidates)
        {
            foreach (INamedTypeSymbol contract in implementation.AllInterfaces)
            {
                if (!Matches(contract, serviceType))
                {
                    continue;
                }

                body.AppendLine(
                    $"        services.Add{lifetime}(typeof({contract.ToDisplayString()}), typeof({implementation.ToDisplayString()}));");
            }
        }
    }

    /// <summary>
    /// Whether an implemented interface satisfies the requested service type. A closed request
    /// (<c>IHandler&lt;Order&gt;</c>) matches only that interface; an open one
    /// (<c>IHandler&lt;&gt;</c>) matches every closed form of it.
    /// </summary>
    /// <remarks>
    /// Compared through <see cref="ISymbol.OriginalDefinition"/> on both sides: the symbol for
    /// <c>typeof(IHandler&lt;&gt;)</c> in an attribute argument is an unbound generic, which is not
    /// the same symbol as the interface definition a type is recorded as implementing.
    /// </remarks>
    private static bool Matches(INamedTypeSymbol contract, INamedTypeSymbol serviceType)
    {
        if (SymbolEqualityComparer.Default.Equals(contract, serviceType))
        {
            return true;
        }

        return serviceType.IsUnboundGenericType
            && contract.IsGenericType
            && SymbolEqualityComparer.Default.Equals(contract.OriginalDefinition, serviceType.OriginalDefinition);
    }

    private static string LifetimeOf(AttributeData request)
    {
        foreach (KeyValuePair<string, TypedConstant> named in request.NamedArguments)
        {
            if (named.Key == "Lifetime" && named.Value.Value is int value)
            {
                return value switch
                {
                    0 => "Singleton",
                    1 => "Scoped",
                    2 => "Transient",
                    _ => "Scoped",
                };
            }
        }

        return "Scoped";
    }

    /// <summary>
    /// Every concrete type declared in this compilation. The scan happens here, at compile time,
    /// which is the entire point — the emitted method contains literal registrations.
    /// </summary>
    private static IEnumerable<INamedTypeSymbol> ConcreteTypesIn(Compilation compilation)
    {
        var queue = new Queue<INamespaceOrTypeSymbol>();
        queue.Enqueue(compilation.Assembly.GlobalNamespace);

        while (queue.Count > 0)
        {
            INamespaceOrTypeSymbol current = queue.Dequeue();

            foreach (ISymbol member in current.GetMembers())
            {
                switch (member)
                {
                    case INamespaceSymbol nested:
                        queue.Enqueue(nested);
                        break;

                    case INamedTypeSymbol { TypeKind: TypeKind.Class, IsAbstract: false, IsGenericType: false } type:
                        queue.Enqueue(type);
                        yield return type;
                        break;

                    case INamedTypeSymbol type:
                        queue.Enqueue(type);
                        break;
                }
            }
        }
    }
}
