using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Brama.SourceGenerator.Contracts;
using Microsoft.CodeAnalysis;

namespace Brama.SourceGenerator;

/// <summary>
/// Brama's Roslyn incremental source generator.
/// </summary>
/// <remarks>
/// This generator is deliberately side-effect-free: it emits source and diagnostics and nothing
/// else. It runs on every IDE design-time build, so anything it wrote to the tracked source tree
/// would be rewritten on every keystroke. File-writing responsibilities (the Contracts snapshot)
/// belong to the companion MSBuild target, which runs only on real builds.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class BramaGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static postInitializationContext =>
            postInitializationContext.AddSource(
                "Brama.Generated.Greeting.g.cs",
                """
                // <auto-generated/>
                #nullable enable

                namespace Brama.Generated;

                public static class Greeting
                {
                    public const string Message = "Hello from the Brama source generator!";
                }
                """));

        IncrementalValuesProvider<ProblemDetailsAnalysis> problemDetails = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => ProblemDetailsAnalyzer.IsCandidate(node),
                transform: static (syntaxContext, cancellationToken) =>
                    ProblemDetailsAnalyzer.Analyze(syntaxContext, cancellationToken))
            .Where(static analysis => analysis is not null)
            .Select(static (analysis, _) => analysis!);

        context.RegisterSourceOutput(problemDetails.Collect(), static (sourceProductionContext, analyses) =>
            Report(sourceProductionContext, analyses));

        IncrementalValuesProvider<INamedTypeSymbol> modules = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => ModuleEmitter.IsCandidate(node),
                transform: static (syntaxContext, cancellationToken) =>
                    ModuleEmitter.ModuleOf(syntaxContext, cancellationToken))
            .Where(static module => module is not null)
            .Select(static (module, _) => module!);

        context.RegisterSourceOutput(
            modules.Combine(context.CompilationProvider),
            static (sourceProductionContext, pair) =>
            {
                (string hintName, string source) = ModuleEmitter.Emit(pair.Left, pair.Right);
                sourceProductionContext.AddSource(hintName, source);
            });
    }

    /// <summary>
    /// Writes the API surface out as generated source.
    /// </summary>
    /// <remarks>
    /// A generator may not touch the file system — Roslyn's own analyzer rules forbid it, and with
    /// good reason, since this runs on every keystroke. Generated source, however, lands under
    /// <c>obj/</c> when the project opts into <c>EmitCompilerGeneratedFiles</c>, which is untracked
    /// build output and therefore safe to rewrite continuously. Brama's MSBuild target — which runs
    /// only on a real build — reads it from there and decides what, if anything, to commit.
    /// </remarks>
    private static void EmitContracts(SourceProductionContext context, IEnumerable<ContractGroup> contracts)
    {
        var emitted = new HashSet<string>(StringComparer.Ordinal);
        var source = new StringBuilder();

        source.AppendLine("// <auto-generated/>");
        source.AppendLine("// Brama API surface, read by the Contracts build step. Comments only: nothing here compiles.");

        foreach (ContractGroup group in contracts)
        {
            string identity = $"{group.Name}.v{group.Version.ToString(CultureInfo.InvariantCulture)}";
            if (!emitted.Add(identity))
            {
                continue;
            }

            source.AppendLine();
            source.Append("// BRAMA-CONTRACT-BEGIN ").AppendLine(identity);

            if (group.AcceptBreakingChangeReason is { } reason)
            {
                source.Append("// BRAMA-ACCEPT-BREAKING ").AppendLine(reason.Replace('\n', ' ').Replace('\r', ' '));
            }

            foreach (string line in ContractFacts.Write(group).Split('\n'))
            {
                source.Append("// ").AppendLine(line.TrimEnd('\r'));
            }

            source.AppendLine("// BRAMA-CONTRACT-END");
        }

        context.AddSource("Brama.Contract.g.cs", source.ToString());
    }

    private static void Report(SourceProductionContext context, ImmutableArray<ProblemDetailsAnalysis> analyses)
    {
        EmitContracts(context, analyses.SelectMany(analysis => analysis.Contracts));

        foreach (ProblemDetailsAnalysis analysis in analyses)
        {
            if (analysis.EscapedTo is { } escapedTo)
            {
                context.ReportDiagnostic(Diagnostic.Create(
                    BramaDiagnostics.ConfigurationNotStaticallyAnalyzable,
                    analysis.Location,
                    escapedTo));

                continue;
            }

            foreach (string missing in analysis.MissingKinds)
            {
                context.ReportDiagnostic(Diagnostic.Create(
                    BramaDiagnostics.MissingErrorKindMapping,
                    analysis.Location,
                    missing));
            }
        }
    }
}
