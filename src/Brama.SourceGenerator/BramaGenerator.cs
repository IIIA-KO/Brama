using Microsoft.CodeAnalysis;

namespace Brama.SourceGenerator;

/// <summary>
/// Brama's Roslyn incremental source generator.
/// </summary>
/// <remarks>
/// This generator is deliberately side-effect-free: it emits source and diagnostics and nothing
/// else. It runs on every IDE design-time build, so anything it wrote to the tracked source tree
/// would be rewritten on every keystroke. File-writing responsibilities (the Contracts snapshot)
/// belong to the companion MSBuild target, which runs only on real builds.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class BramaGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static postInitializationContext =>
            postInitializationContext.AddSource(
                "Brama.Generated.Greeting.g.cs",
                """
                // <auto-generated/>
                #nullable enable

                namespace Brama.Generated;

                public static class Greeting
                {
                    public const string Message = "Hello from the Brama source generator!";
                }
                """));
    }
}
